// 自然语言提醒的哨兵协议。
//
// 用户说「这周四下午4点钟提醒张总去占位置」时，这句话进不了 /提醒 那条
// 代码路径（不以 /提醒 开头），于是落到模型路径上——而模型**没有任何工具能写
// jobs.json**，它顶多回一句「好的，记下了」，实际什么都不会发生。它会假装成功，
// 用户要到错过提醒之后才发现。
//
// 解法是让模型只做**翻译**：把自然语言改写成 qqbot 听得懂的语法，写成一行哨兵；
// 代码解析哨兵、用 reminders.js 的 parseReminder 校验、再落盘。
// 模型永远不碰 jobs.json —— 与「加人/移出用户」同一条红线（见 reminders.js 文件头）。
//
// 为什么用哨兵而不是让模型直接输出 /提醒 命令：模型一旦输出可执行文本，
// 下一步就是有人把它当命令执行。哨兵是明确的"数据"边界，代码只从哨兵里取内容。
//
// 为什么要求**独占一行**：与 message.js 的 <<END>> 同款理由——模型在解释这套
// 机制时会提到哨兵本身（"我会输出 <<提醒 …>>"），行内出现不该触发。

export const REMIND_MARK = "<<提醒";

// 模型判定"这句话不是提醒请求"时的明确回绝。
//
// 存在的意义是让「提醒我一下这个功能怎么用」这类**只是提到提醒**的消息有确定
// 行为：模型给一个明确的"不"，比让它硬凑一条提醒、或者干脆不输出（与"输出格式
// 坏了"无法区分）都可靠。
export const REMIND_NONE = "<<无提醒>>";

// 从模型输出里取哨兵内容。
//
// 返回：
//   { text }       —— 哨兵里的翻译结果，交给调用方拼成 /提醒 <text> 再解析
//   { none: true } —— 模型明确表示这不是提醒请求
//   null           —— 没找到哨兵（模型没按格式输出，或输出坏了）
//
// 三种情况必须分开：调用方的回执文案不同（"这不是提醒请求" vs "没听懂，请用
// /提醒 格式"），混成一种会让用户不知道该怎么改写。
export function parseReminderSentinel(raw) {
  const text = String(raw ?? "");

  // 先看回绝。它也要求独占一行，理由同上。
  for (const line of text.split("\n")) {
    if (line.trim() === REMIND_NONE) return { none: true };
  }

  // 哨兵本体：整行恰好是 <<提醒 …>>，前后只有空白。
  //
  // 用整行匹配而不是全文搜索：`<<提醒` 出现在句子中间时（解释机制、引用格式）
  // 不该被当成协议。内层允许换行以外的任意字符，且必须非空——空的
  // `<<提醒 >>` 没有可解析的内容，与"没找到"等价。
  const m = /^[ \t]*<<提醒\s+([\s\S]*?)\s*>>[ \t]*$/m.exec(text);
  if (!m) return null;
  const inner = m[1].trim();
  if (!inner) return null;
  return { text: inner };
}
